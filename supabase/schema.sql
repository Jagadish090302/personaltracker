-- Black Notebook v1 database schema
-- Run this file in Supabase Dashboard > SQL Editor.
-- All personal rows are scoped to the authenticated user via Row Level Security.

create table if not exists public.daily_logs (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  log_date date not null,
  category text not null check (category in ('discipline', 'skills', 'income', 'fitness', 'content', 'focus')),
  completed boolean not null default false,
  note text not null default '',
  minutes integer not null default 0 check (minutes >= 0 and minutes <= 1440),
  plan_start date not null default current_date,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, log_date, category)
);

create index if not exists daily_logs_user_date_idx
  on public.daily_logs (user_id, log_date desc);

alter table public.daily_logs enable row level security;

-- Recreate only this table's policies so re-running the script is safe.
drop policy if exists "Users can read their own daily logs" on public.daily_logs;
drop policy if exists "Users can insert their own daily logs" on public.daily_logs;
drop policy if exists "Users can update their own daily logs" on public.daily_logs;
drop policy if exists "Users can delete their own daily logs" on public.daily_logs;

create policy "Users can read their own daily logs"
  on public.daily_logs for select to authenticated
  using ((select auth.uid()) = user_id);

create policy "Users can insert their own daily logs"
  on public.daily_logs for insert to authenticated
  with check ((select auth.uid()) = user_id);

create policy "Users can update their own daily logs"
  on public.daily_logs for update to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

create policy "Users can delete their own daily logs"
  on public.daily_logs for delete to authenticated
  using ((select auth.uid()) = user_id);

-- Restrict table access to signed-in users; RLS still filters rows by user_id.
revoke all on public.daily_logs from anon;
grant select, insert, update, delete on public.daily_logs to authenticated;
grant usage, select on sequence public.daily_logs_id_seq to authenticated;

-- Optional: automatically keep updated_at current.
create or replace function public.set_daily_logs_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists set_daily_logs_updated_at on public.daily_logs;
create trigger set_daily_logs_updated_at
before update on public.daily_logs
for each row execute procedure public.set_daily_logs_updated_at();